import fs from 'node:fs/promises';
import {createHash} from 'node:crypto';
import {Script} from 'node:vm';
import {paper} from './paper.mjs';
import {project} from './project.mjs';
import {pagingFigure,traceFigure} from './figures.mjs';
const archive='D:/Agent-Proj/jarvis-reading-samples';
const base='http://127.0.0.1:3100';
if(!process.env.AUTHOR_TOKEN)throw Error('Use existing local author environment');
const headers={Authorization:`Bearer ${process.env.AUTHOR_TOKEN}`};
const context=await fetch(base+'/api/author',{headers});if(!context.ok)throw Error('Author context: '+context.status);
const lib=await context.json();
const metadata=JSON.parse(await fs.readFile(archive+'/pagedattention/raw/hf-metadata.json','utf8'));
const sourceHash=createHash('sha256').update(metadata.title+'\n'+metadata.summary).digest('hex');
const entry={id:paper.itemId,kind:'paper',title:metadata.title,summary:metadata.summary,url:'https://huggingface.co/papers/2309.06180',pdfUrl:'https://arxiv.org/pdf/2309.06180',codeUrl:'https://github.com/vllm-project/vllm',rank:0,authors:['Woosuk Kwon','Zhuohan Li','Siyuan Zhuang','Ying Sheng','Lianmin Zheng','Cody Hao Yu','Joseph E. Gonzalez','Hao Zhang','Ion Stoica'],published:'2023-09-12',sourceHash};
const known=new Map(lib.boards.flatMap(b=>b.items).map(e=>[e.id,e]));
const projectEntry=known.get(project.itemId);if(!projectEntry)throw Error('Today project entry unavailable');
const generatedAt=new Date().toISOString();
for(const figure of [pagingFigure,traceFigure])for(const match of figure.html.matchAll(/<script>([\s\S]*?)<\/script>/g))new Script(match[1],{filename:figure.title});
paper.sections[3].figure=pagingFigure;project.sections[6].figure=traceFigure;
const readings=[{...paper,sourceHash,entry},{...project,sourceHash:projectEntry.sourceHash}].map(r=>({...r,generatedAt,author:'Codex · 问题驱动精读样章'}));
await fs.mkdir(archive+'/outputs',{recursive:true});
await fs.writeFile(archive+'/outputs/readings.json',JSON.stringify(readings,null,2));
const output=await fetch(base+'/api/author',{method:'POST',headers:{...headers,'Content-Type':'application/json'},body:JSON.stringify(readings)});
const result=await output.json();if(!output.ok)throw Error(JSON.stringify(result));
const receipt={...result,generatedAt,visibility:'draft',readings:readings.map(r=>({itemId:r.itemId,sections:r.sections.length,characters:r.sections.reduce((n,s)=>n+s.body.length,0),source:r.study.sourceSnapshot}))};
await fs.writeFile(archive+'/outputs/import-receipt.json',JSON.stringify(receipt,null,2));console.log(JSON.stringify(receipt));
